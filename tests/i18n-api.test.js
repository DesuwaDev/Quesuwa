import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createApp } from '../server/app.js';

test('API language, CSV, stable status IDs and legacy migration preserve answers', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'quesuwa-i18n-'));
  let instance = createApp({ dataDir: dir, password: 'i18n-test-password-12345' });
  const database = new DatabaseSync(path.join(dir, 'report.sqlite'));
  const snapshot = { id: 'form', title: '用户自定义标题', fields: [{ id: 'answer', type: 'short', label: '用户题目' }] };
  const now = new Date().toISOString();
  database.prepare('INSERT INTO forms(id,slug,state,version,definition,created_at,updated_at) VALUES (?,?,?,?,?,?,?)').run('form', 'locale-test', 'published', 1, JSON.stringify({ ...snapshot, slug: 'locale-test', state: 'published' }), now, now);
  const insert = database.prepare('INSERT INTO responses (id,form_id,snapshot,answers,attachments,created_at,status) VALUES (?,?,?,?,?,?,?)');
  for (const [index, status] of ['待处理', '排查中', '已解决', '需要补充'].entries()) insert.run(`response-${index}`, 'form', JSON.stringify(snapshot), JSON.stringify({ answer: '保留原始答卷内容' }), '[]', now, status);
  database.close(); instance.close();
  instance = createApp({ dataDir: dir, password: 'i18n-test-password-12345' });
  const server = instance.app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { await new Promise(resolve => server.close(resolve)); instance.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  let res = await fetch(base + '/api/admin/forms', { headers: { 'Accept-Language': 'en-US' } });
  assert.equal(res.status, 401); assert.equal(res.headers.get('content-language'), 'en');
  assert.deepEqual(await res.json(), { code: 'errors.loginRequired', params: {}, error: 'Please sign in to the admin workspace.' });
  res = await fetch(base + '/api/admin/forms', { headers: { 'Accept-Language': 'zh-CN' } });
  assert.equal((await res.json()).error, '请先登录管理后台');
  res = await fetch(base + '/api/admin/login', { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json' }, body: JSON.stringify({ password: 'i18n-test-password-12345' }) });
  const cookie = res.headers.get('set-cookie').split(';')[0];
  res = await fetch(base + '/api/admin/forms/form/responses', { headers: { Cookie: cookie, 'Accept-Language': 'en' } });
  const data = await res.json();
  assert.deepEqual(data.items.map(x => x.status).sort(), ['pending', 'inProgress', 'resolved', 'needsInfo'].sort());
  assert.equal(data.items[0].snapshot.title, '用户自定义标题');
  assert.equal(data.items[0].answers.answer, '保留原始答卷内容');
  res = await fetch(base + '/api/admin/forms/form/export?lang=en', { headers: { Cookie: cookie, 'Accept-Language': 'zh-CN' } });
  const english = await res.text();
  assert.match(english, /Response ID/); assert.match(english, /In progress/); assert.match(english, /用户题目/); assert.match(english, /保留原始答卷内容/); assert.doesNotMatch(english, /待处理/);
  res = await fetch(base + '/api/admin/forms/form/export?lang=zh-CN', { headers: { Cookie: cookie } });
  assert.match(await res.text(), /待处理/);
  res = await fetch(base + '/api/admin/forms', { method: 'POST', headers: { Cookie: cookie, Origin: base, 'Content-Type': 'application/json', 'Accept-Language': 'en' }, body: '{}' });
  assert.equal(res.status, 400); const validation = await res.json(); assert.equal(validation.code, 'errors.textInvalid'); assert.match(validation.error, /Link slug/);
  for (let i = 0; i < 10; i++) res = await fetch(base + '/api/admin/login', { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json', 'Accept-Language': 'en' }, body: '{"password":"wrong"}' });
  assert.equal(res.status, 429); assert.equal((await res.json()).error, 'Too many attempts. Please try again later.');
});
